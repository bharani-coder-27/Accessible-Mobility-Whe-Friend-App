export type TranslateParams = Record<string, string | number>;

/**
 * Look up a string and substitute any `{placeholder}` tokens.
 *
 * Placeholders rather than string concatenation, because word order differs
 * between these three languages — "5 km away" and "{distance} கி.மீ. தொலைவில்"
 * cannot be assembled from the same fragments in the same order.
 */
export const translate = (
  language: Language,
  key: TranslationKey,
  params?: TranslateParams
) => {
  const template = translations[language][key] ?? translations.en[key];
  if (!params) return template;

  return Object.entries(params).reduce(
    (result, [token, value]) => result.split(`{${token}}`).join(String(value)),
    template
  );
};
